"""Generate raster, platform, favicon, and native-vector assets from one SVG."""

from __future__ import annotations

import hashlib
import json
import re
import shutil
import subprocess
import tempfile
import xml.etree.ElementTree as ET
from pathlib import Path

from PIL import Image

ROOT = Path(__file__).resolve().parents[1]
WINDOWS = Path("apps/windows/NaumiAgentWorkbench/src-tauri/icons")
MACOS = Path("apps/macos/NaumiAgentWorkbench")
PUBLIC = Path("frontend/web/public")
SWIFT = MACOS / "Sources/NaumiAgentWorkbenchCore/Components/NaumiBrandMark.swift"
PNG_SIZES = {
    "icon.png": 512,
    "32x32.png": 32,
    "128x128.png": 128,
    "128x128@2x.png": 256,
    "StoreLogo.png": 50,
    **{f"Square{s}x{s}Logo.png": s for s in (30, 44, 71, 89, 107, 142, 150, 284, 310)},
}


def native_mark(svg: Path) -> str:
    """Compile the intentionally small rect/polyline SVG into a native SwiftUI view."""
    tree = ET.parse(svg).getroot()
    ns = {"s": "http://www.w3.org/2000/svg"}
    rect, line = tree.find("s:rect", ns), tree.find("s:path", ns)
    if rect is None or line is None or tree.attrib["viewBox"] != "0 0 128 128":
        raise ValueError("品牌 SVG 必须包含 128 坐标系的圆角底板与 N 路径")
    data = line.attrib["d"]
    if not re.fullmatch(r"M\d+ \d+(?:L\d+ \d+)+", data):
        raise ValueError("品牌路径仅支持绝对 M/L 坐标，请同步更新原生编译器")
    points = re.findall(r"[ML](\d+) (\d+)", data)
    commands = "\n".join(
        f"            mark.{'move' if i == 0 else 'addLine'}(to: CGPoint(x: {x}, y: {y}))"
        for i, (x, y) in enumerate(points)
    )
    color = rect.attrib["fill"].lstrip("#")
    red, green, blue = (int(color[i : i + 2], 16) for i in (0, 2, 4))
    return f"""// Generated by scripts/generate_brand_assets.py from assets/logo.svg.
import SwiftUI

public struct NaumiBrandMark: View {{
    private let size: CGFloat

    public init(size: CGFloat = 20) {{
        self.size = size
    }}

    public var body: some View {{
        Canvas {{ context, canvasSize in
            context.scaleBy(x: canvasSize.width / 128, y: canvasSize.height / 128)
            let tile = Path(roundedRect: CGRect(x: 0, y: 0, width: 128, height: 128),
                            cornerRadius: {rect.attrib["rx"]})
            context.fill(tile, with: .color(Color(red: {red}.0 / 255,
                                                green: {green}.0 / 255,
                                                blue: {blue}.0 / 255)))
            var mark = Path()
{commands}
            context.stroke(mark, with: .color(.white),
                           style: StrokeStyle(lineWidth: {line.attrib["stroke-width"]},
                                              lineCap: .round, lineJoin: .round))
        }}
        .frame(width: size, height: size)
        .accessibilityLabel("NaumiAgent")
    }}
}}
"""


def generate() -> dict[str, str]:
    # Prepare every output before publishing, so a renderer failure preserves existing assets.
    with tempfile.TemporaryDirectory(prefix="naumi-brand-") as temporary:
        stage = Path(temporary)

        def target(relative: Path) -> Path:
            result = stage / relative
            result.parent.mkdir(parents=True, exist_ok=True)
            return result

        logo = Path("assets/logo.png")
        swift = native_mark(ROOT / "assets/logo.svg")
        subprocess.run(
            ["node", str(ROOT / "scripts/render-brand-assets.mjs"), str(target(logo))],
            check=True,
        )
        with Image.open(stage / logo) as source:
            tile = source.convert("RGBA")
        outputs = [logo]
        for name, size in PNG_SIZES.items():
            asset = WINDOWS / name
            tile.resize((size, size), Image.Resampling.LANCZOS).save(target(asset))
            outputs.append(asset)
        ico, icns = WINDOWS / "icon.ico", WINDOWS / "icon.icns"
        tile.save(target(ico), sizes=[(s, s) for s in (16, 24, 32, 48, 64, 128, 256)])
        tile.save(target(icns))
        outputs.extend([ico, icns])
        target(SWIFT).write_text(swift, encoding="utf-8", newline="\n")
        outputs.append(SWIFT)
        for dest, source in {
            MACOS / "Resources/AppIcon.icns": stage / icns,
            PUBLIC / "brand-mark.svg": ROOT / "assets/logo.svg",
            PUBLIC / "favicon.ico": stage / ico,
        }.items():
            shutil.copyfile(source, target(dest))
            outputs.append(dest)
        touch = PUBLIC / "apple-touch-icon.png"
        opaque = Image.new("RGBA", tile.size, "#181B23")
        opaque.alpha_composite(tile)
        opaque.convert("RGB").resize((180, 180), Image.Resampling.LANCZOS).save(target(touch))
        outputs.append(touch)
        hashes = {
            p.as_posix(): hashlib.sha256((stage / p).read_bytes()).hexdigest() for p in outputs
        }
        manifest = {
            "source": "assets/logo.svg",
            "source_sha256": hashlib.sha256((ROOT / "assets/logo.svg").read_bytes()).hexdigest(),
            "palette": ["#181B23", "#FFFFFF"],
            "outputs": hashes,
        }
        manifest_path = Path("assets/brand-manifest.json")
        target(manifest_path).write_text(
            json.dumps(manifest, indent=2) + "\n", encoding="utf-8", newline="\n"
        )
        for relative in [*outputs, manifest_path]:
            (ROOT / relative).parent.mkdir(parents=True, exist_ok=True)
            shutil.copyfile(stage / relative, ROOT / relative)
        return hashes


if __name__ == "__main__":
    print(f"品牌资产已生成：{len(generate())} 个文件")
